// Puts the icon sources design/icons/*.svg into one SVG sprite for the app,
// assets/icons/sprite.svg, one <symbol id="name"> per icon (specification 7.4).
//
//   node tools/icon-sprite.mjs
//
// The sources are drawn on a 24×24 grid with a few element classes:
//   s  = stroke (1.75, round caps and joins; `stroke-width` may override)
//   f  = second tone: fill at reduced opacity
//   sf = both
//   d  = solid fill (dots, small details)
// In the sprite the classes become plain SVG attributes with currentColor, so an icon takes the color of the text
// around it, in any theme and area color. Like in Cleanerr, all second-tone fills are drawn first, then the
// strokes, then the solid details. A unit test checks the sprite is up to date.

import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SOURCE = 'design/icons/';
export const SPRITE = 'assets/icons/sprite.svg';
const STROKE = '1.75';
const TONE_OPACITY = '0.22';

const ELEMENT = /<(path|circle|ellipse|rect|line)\b([^>]*?)\/>/g;
const ATTRIBUTE = /([a-z-]+)="([^"]*)"/g;

function attributes(text) {
  return Object.fromEntries([...text.matchAll(ATTRIBUTE)].map((m) => [m[1], m[2]]));
}

function element(tag, attrs) {
  return `<${tag} ${Object.entries(attrs).map(([k, v]) => `${k}="${v}"`).join(' ')}/>`;
}

/** The layers of one icon: fills, strokes, solids. */
export function symbol(name, svg) {
  const fills = [];
  const strokes = [];
  const solids = [];
  for (const [, tag, rest] of svg.matchAll(ELEMENT)) {
    const { class: cls = 's', 'stroke-width': width, ...shape } = attributes(rest);
    if (!['s', 'f', 'sf', 'd'].includes(cls)) throw new Error(`${name}: unknown class '${cls}'`);
    if (cls.includes('f')) fills.push(element(tag, { ...shape, fill: 'currentColor', 'fill-opacity': TONE_OPACITY }));
    if (cls.includes('s')) strokes.push(element(tag, { ...shape, 'stroke-width': width ?? STROKE }));
    if (cls === 'd') solids.push(element(tag, { ...shape, fill: 'currentColor' }));
  }
  if (fills.length + strokes.length + solids.length === 0) throw new Error(`${name}: no shapes`);
  const parts = [...fills];
  if (strokes.length) parts.push(`<g fill="none" stroke="currentColor" stroke-linecap="round" stroke-linejoin="round">${strokes.join('')}</g>`);
  parts.push(...solids);
  return `<symbol id="${name}" viewBox="0 0 24 24">${parts.join('')}</symbol>`;
}

/** The sprite for the current sources. */
export async function sprite() {
  const files = (await readdir(ROOT + SOURCE)).filter((file) => file.endsWith('.svg')).sort();
  const symbols = await Promise.all(files.map(async (file) => symbol(file.slice(0, -4), await readFile(ROOT + SOURCE + file, 'utf8'))));
  return [
    `<!-- GENERATED by tools/icon-sprite.mjs from ${SOURCE}*.svg. Do not edit by hand. -->`,
    '<svg xmlns="http://www.w3.org/2000/svg">',
    ...symbols.map((s) => `  ${s}`),
    '</svg>',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await sprite();
  await writeFile(ROOT + SPRITE, text);
  console.log(`${SPRITE}: ${(text.match(/<symbol /g) ?? []).length} icons`);
}
